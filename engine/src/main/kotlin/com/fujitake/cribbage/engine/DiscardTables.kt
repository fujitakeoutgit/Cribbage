package com.fujitake.cribbage.engine

/**
 * How strong players discard, per seat. Index 0 is the dealer's habits, index 1 the non-dealer's.
 *
 * [throwRate] is the chance a given pair of ranks is thrown when it is in a six-card hand, indexed
 * by `rank * 14 + rank`. [keepRate] is the chance a dealt rank is kept, indexed by rank.
 */
class DiscardTables(
    private val throwRate: Array<DoubleArray>,
    private val keepRate: Array<DoubleArray>,
) {
    fun throwWeight(dealer: Boolean, rankA: Int, rankB: Int): Double =
        throwRate[seat(dealer)][pairIndex(rankA, rankB)]

    fun keepWeights(dealer: Boolean): DoubleArray = keepRate[seat(dealer)]

    fun serialize(): String = buildString {
        for (seat in 0..1) {
            appendLine(throwRate[seat].joinToString(" ") { "%.6f".format(java.util.Locale.ROOT, it) })
            appendLine(keepRate[seat].joinToString(" ") { "%.6f".format(java.util.Locale.ROOT, it) })
        }
    }

    private fun seat(dealer: Boolean) = if (dealer) 0 else 1

    companion object {
        const val PAIR_SLOTS = 14 * 14

        fun pairIndex(rankA: Int, rankB: Int) = minOf(rankA, rankB) * 14 + maxOf(rankA, rankB)

        /** Every discard and keep treated as equally likely. Used to start table generation. */
        val UNIFORM = DiscardTables(
            Array(2) { DoubleArray(PAIR_SLOTS) { 1.0 } },
            Array(2) { DoubleArray(14) { 1.0 } },
        )

        fun parse(text: String): DiscardTables {
            val rows = text.lines().filter { it.isNotBlank() }
                .map { line -> line.trim().split(' ').map(String::toDouble).toDoubleArray() }
            return DiscardTables(arrayOf(rows[0], rows[2]), arrayOf(rows[1], rows[3]))
        }

        /** The tables generated by `:tablegen` and shipped as a resource. */
        val bundled: DiscardTables by lazy {
            val stream = requireNotNull(DiscardTables::class.java.getResourceAsStream("/discard_tables.txt")) {
                "discard_tables.txt is missing; run :tablegen:run"
            }
            parse(stream.bufferedReader().use { it.readText() })
        }
    }
}
